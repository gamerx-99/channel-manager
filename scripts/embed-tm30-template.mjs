// Regenerates server/tm30OfficialTemplate.ts from the Immigration Bureau's TM.30 import template.
//
// Cloudflare Workers have no filesystem, so the official .xls is embedded as base64.
// Usage: node scripts/embed-tm30-template.mjs path/to/Template-InformAccom-ImportExcel.xls
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const source = process.argv[2];
if (!source) {
  console.error("Usage: node scripts/embed-tm30-template.mjs <path to Template-InformAccom-ImportExcel.xls>");
  process.exit(1);
}

const bytes = readFileSync(source);
const base64 = bytes.toString("base64");
const lines = base64.match(/.{1,110}/g) ?? [];
const sha256 = createHash("sha256").update(bytes).digest("hex");

const output = `// GENERATED by scripts/embed-tm30-template.mjs. Do not edit by hand.
// Source: Immigration Bureau TM.30 import template "Template-InformAccom-ImportExcel.xls" (${bytes.length} bytes).
// SHA-256: ${sha256}
export const TM30_OFFICIAL_TEMPLATE_SHA256 = "${sha256}";
export const TM30_OFFICIAL_TEMPLATE_BASE64 = [
${lines.map(line => `  "${line}",`).join("\n")}
].join("");
`;

writeFileSync(new URL("../server/tm30OfficialTemplate.ts", import.meta.url), output);
console.log(`Wrote server/tm30OfficialTemplate.ts (${bytes.length} bytes, ${lines.length} lines)`);
